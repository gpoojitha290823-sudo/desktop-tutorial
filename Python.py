#Comparison operators

#Less than(<)
a = 2026
b = 2030
print(a<b)

l = 100
k = 50
print(l<k)

#Greater than(>)
m = 369
n = 966
print(m>n)

q = 46575
w = 464979
print(q>w)

#Not equal to (!=)
x = 566
y = 980
print(x!=y)

r = 87
t = 88
print(r!=t)

#Greater than or equal to(>=)
marks = 66
print(marks>=70)

pulse = 71
