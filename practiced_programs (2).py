#Check even or odd
n = int(input("Enter a number: "))

if n % 2 == 0:
  print("Even")
else:
  print("Odd")

#Find the bigger number
a = int(input("Enter a first number: "))
b = int(input("Enter a second number: "))
if a > b:
   print("Bigger: ",a)
else:
  print("Bigger: ",b)
