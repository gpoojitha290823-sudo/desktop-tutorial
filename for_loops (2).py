#for loops
#print numbers with condition
for i in range(2, 21, 2):
  print(i)


#Find the sum of two numbers
total = 0

for i in range(1,10):
  total = total + i
print("sum = ", total)

#Iterate through a list
fruits = ["Apple", "Mango", "Grapes", "Orange"]

for fruit in fruits:
  print(fruit)


#Iterate through a string
name = "PYTHON"

for ch in name:
  print(ch)

#Reverse counting
for i in range(10, 0, -1):
  print(i)
