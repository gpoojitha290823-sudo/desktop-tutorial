#String slicing
str_1 = "Yogitha"
print(str_1[4])
print(str_1[2])
print(str_1[6])
print(str_1[0])
print(str_1[-1])
print(str_1[-5])
print(str_1[-3])

#string[start:stop]
str_2 = "Harini"
print(str_2[3:7])
print(str_2[5:5])
print(str_2[0:4])
print(str_2[ :2])
print(str_2[ :6])
print(str_2[2: ])
print(str_2[:])

#string[start:stop:step]
str_3 = "Python"
print(str_3[0:6:2])
print(str_3[2:5:3])
print(str_3[0:4:1])
print(str_3[3: :-2])
