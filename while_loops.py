#while loops
#print numbers from 0 to 1o
i = 0

while i <= 10:
  print(i)
  i += 1

#print numbers from 10 to 1
a = 10

while a >= 1:
  print(a)
  a -= 1

#print even numbers from 1 to 15
num = 2

while num <= 15:
  print(num)
  num += 2

#sum of numbers from 1 to 10
i = 1
total = 0

while i <= 10:
  total = total + i
  i += 1
print("Sum:", total)
