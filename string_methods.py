#String methods

#Upper()
name = 'poojitha'
upper_result = name.upper()
print(upper_result)

name = "yogitha"
upper_result = name.upper()
print(upper_result)

#Lower()
name_2 = 'PYTHON'
lower_result = name_2.lower()
print(lower_result)

name_3 = 'JAVA'
lower_result = name_3.lower()
print(lower_result)

#Strip()
str = '  Hello world  '
result = str.strip()
print(result)

str = "Heyy Alice"
result = str.strip()
print(result)

#replace(old)
split_words = "Hello world"
result = split_words.replace("Hello", 'Hii')
print(result)

split_words = 'Hii Poojitha'
result = split_words.replace('Hii', 'Hello')
print(result)               
